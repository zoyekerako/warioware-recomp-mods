#!/usr/bin/env python3
"""Translate a beatscript source (.bs) into C.

The GBA build assembles .bs directly: every pointer in a script is a four-byte
.word.  A 64-bit host cannot use that -- the addresses would be truncated -- so
the same data has to be laid out by the host compiler instead.

Rather than reimplement the fifty-odd macros in include/beatscript_main.inc,
this assembles the file with the real assembler and reads the result back:
the section bytes give the literals, the relocations give the symbols, and the
global labels give the array boundaries.  The .bs source is consulted only for
whether a label names a script, a struct or a text block.

Referenced symbols are declared with an explicit assembler name
(`extern char bs_ref_x[] __asm__("_x")`), so the generated file never has to
agree with any header about their types.
"""

import argparse
import os
import re
import struct
import subprocess
import sys

REPO_DEFAULT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "..", "..", "wariowareinc-main")
SIZEOF_BEATSCRIPT = 12   # command:8 + param1:24, param2, param3
SIZEOF_SUBSCENE = 36     # four (function, argument) pairs plus the script


def run(cmd, cwd=None):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=cwd)
    if r.returncode:
        sys.exit("%s failed:\n%s" % (cmd.split()[0], (r.stderr or r.stdout)[:2000]))
    return r.stdout


def label_kinds(path):
    """Read the .bs source for `script`/`struct`/`text` labels, in order."""
    kinds = {}
    for line in open(path):
        m = re.match(r"\s*(script|struct|text)\s+(\w+)\s*$", line)
        if m:
            kinds[m.group(2)] = m.group(1)
    return kinds


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="path to the .bs file, relative to the repo root")
    ap.add_argument("-o", "--output", help="output .c (default: alongside the source)")
    ap.add_argument("--repo", default=REPO_DEFAULT)
    ap.add_argument("--symbol-prefix", default="_",
                    help="assembler symbol prefix of the host (Mach-O uses '_')")
    ap.add_argument("--verify", action="store_true",
                    help="compile the result for the GBA and diff it against the .bs")
    ap.add_argument("--tmp", default="/tmp/wwbs2c")
    args = ap.parse_args()

    repo = os.path.abspath(args.repo)
    os.makedirs(args.tmp, exist_ok=True)
    src = args.source
    s_f = os.path.join(args.tmp, "a.s")
    o_f = os.path.join(args.tmp, "a.o")

    run("cc -E -I . -iquote include -x assembler-with-cpp %s -o %s" % (src, s_f), cwd=repo)
    run("arm-none-eabi-as -march=armv4t -I . -o %s %s" % (o_f, s_f), cwd=repo)

    # Section bytes.  objcopy -O binary drops a non-alloc section, so read the
    # hex dump instead.
    data = bytearray()
    for line in run("arm-none-eabi-objdump -s --section=.scene %s" % o_f).splitlines():
        m = re.match(r"^\s*([0-9a-f]{4,8})\s((?:[0-9a-f]{2,8}\s){1,4})\s", line)
        if m:
            data.extend(bytes.fromhex(m.group(2).replace(" ", "")))
    data = bytes(data)

    # Relocations: byte offset -> symbol name.
    relocs = {}
    for line in run("arm-none-eabi-objdump -r --section=.scene %s" % o_f).splitlines():
        m = re.match(r"^([0-9a-f]{8})\s+R_ARM_ABS32\s+(\S+)", line)
        if m:
            relocs[int(m.group(1), 16)] = m.group(2)

    # Global labels defined in .scene, and the undefined symbols we reference.
    labels, undefined = [], set()
    for line in run("arm-none-eabi-objdump -t %s" % o_f).splitlines():
        m = re.match(r"^([0-9a-f]{8})\s+g\s+\S*\s*\.scene\s+[0-9a-f]{8}\s+(\S+)$", line)
        if m:
            labels.append((int(m.group(1), 16), m.group(2)))
    labels.sort()
    undefined = {s for s in relocs.values() if s not in {n for _, n in labels}}

    kinds = label_kinds(os.path.join(repo, src))

    local = {n for _, n in labels}

    def word(off):
        """The word at `off`, as a C expression."""
        sym = relocs.get(off)
        if sym is None:
            return "0x%08X" % struct.unpack_from("<I", data, off)[0]
        # A label defined in this same file is referenced by its own name;
        # everything else goes through the type-free alias.
        return "(u32p)%s" % (sym if sym in local else "bs_ref_" + sym)

    out = []
    out.append("/* Generated by port/tools/bs2c.py from %s -- do not edit.\n"
               "   The GBA build assembles the .bs directly; this is the same data\n"
               "   laid out by the host compiler, so its pointers are host-wide. */" % src)
    out.append('#include "global.h"')
    out.append("")
    for sym in sorted(undefined):
        out.append('extern char bs_ref_%s[] __asm__("%s%s");' % (sym, args.symbol_prefix, sym))
    out.append("")

    for i, (off, name) in enumerate(labels):
        end = labels[i + 1][0] if i + 1 < len(labels) else len(data)
        kind = kinds.get(name, "script")
        if kind == "script":
            out.append("const struct Beatscript %s[] = {" % name)
            for p in range(off, end, SIZEOF_BEATSCRIPT):
                w0 = struct.unpack_from("<I", data, p)[0]
                out.append("    { 0x%02X, 0x%06X, %s, %s },"
                           % (w0 & 0xFF, w0 >> 8, word(p + 4), word(p + 8)))
            out.append("};")
        elif kind == "struct":
            out.append("const struct SubScene %s = {" % name)
            for j, what in enumerate(("start", "paused", "update", "stop")):
                out.append("    /* %-6s */ (void (*)())%s, (s32)%s,"
                           % (what, word(off + j * 8), word(off + j * 8 + 4)))
            out.append("    /* script */ (const struct Beatscript *)%s," % word(off + 32))
            out.append("};")
        else:
            out.append("const u8 %s[] = {" % name)
            body = ", ".join("0x%02X" % b for b in data[off:end])
            out.append("    %s" % body)
            out.append("};")
        out.append("")

    # Generated data lives outside the decomp tree: its Makefile globs data/*.c
    # and would then define every scene twice.
    dest = args.output or os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "pcdata",
        os.path.relpath(os.path.splitext(src)[0], "data") + "_bs.c")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    open(dest, "w").write("\n".join(out) + "\n")
    print("%s: %d Labels, %d Symbole, %d Bytes -> %s"
          % (src, len(labels), len(undefined), len(data), dest))

    if args.verify:
        return verify(repo, args, dest, data, relocs)
    return 0


def verify(repo, args, dest, data, relocs):
    """Compile the generated C for the GBA and compare it with the .bs bytes.

    On the GBA u32p is plain u32, so a faithful translation has to reproduce
    the assembled section exactly.  Words that carry a relocation are counted
    separately: the linker fills those in, so their contents differ by design.
    """
    # Regenerate without the host symbol prefix -- ELF has none.
    src_elf = os.path.join(args.tmp, "verify.c")
    text = open(dest).read()
    text = re.sub(r'__asm__\("%s(\w+)"\)' % re.escape(args.symbol_prefix),
                  r'__asm__("\1")', text)
    open(src_elf, "w").write(text)

    i_f = os.path.join(args.tmp, "verify.i")
    s_f = os.path.join(args.tmp, "verify.s")
    o_f = os.path.join(args.tmp, "verify.o")
    run("cc -E -I tools/agbcc -I tools/agbcc/include -I . -iquote include "
        "-nostdinc -undef %s -o %s" % (src_elf, i_f), cwd=repo)
    run("tools/agbcc/bin/agbcc -mthumb-interwork -O2 -w %s -o %s" % (i_f, s_f), cwd=repo)
    with open(s_f, "a") as f:
        f.write('\n.section .note.GNU-stack,"",%progbits\n')
    run("arm-none-eabi-as -march=armv4t -o %s %s" % (o_f, s_f), cwd=repo)

    built = bytearray()
    for line in run("arm-none-eabi-objdump -s --section=.rodata --section=.data %s"
                    % o_f).splitlines():
        m = re.match(r"^\s*([0-9a-f]{4,8})\s((?:[0-9a-f]{2,8}\s){1,4})\s", line)
        if m:
            built.extend(bytes.fromhex(m.group(2).replace(" ", "")))
    built = bytes(built)

    if len(built) != len(data):
        print("  NICHT DECKUNGSGLEICH: %d Bytes erzeugt, %d erwartet"
              % (len(built), len(data)))
        return 1
    reloc_bytes = {o + k for o in relocs for k in range(4)}
    hard = [i for i in range(len(data)) if built[i] != data[i] and i not in reloc_bytes]
    soft = [i for i in range(len(data)) if built[i] != data[i] and i in reloc_bytes]
    print("  Rueckuebersetzung: %d Bytes, %d Abweichungen (%d an Relocation-Stellen)"
          % (len(built), len(hard), len(soft)))
    if hard:
        for i in hard[:8]:
            print("    +0x%04X: C 0x%02X, .bs 0x%02X" % (i, built[i], data[i]))
        return 1
    print("  IDENTISCH -- die Uebersetzung gibt die .bs-Daten exakt wieder")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
