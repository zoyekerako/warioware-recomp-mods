#!/usr/bin/env python3
"""
Emit the stub file that lets the decompiled game code link on a PC.

Two thirds of what the game references is still assembly or ROM data, so a
straight link fails with a wall of undefined symbols.  Turning each one into a
stub converts that wall into something useful: the build links, the program
runs, and the first thing it actually needs announces itself by name.  That is
a worklist ordered by what the game reaches first, rather than by address.

Functions are told apart from data by looking for a call in the decompiled C --
if the source calls `name(`, it is a function.  Everything else becomes zeroed
storage, sized generously since the real extent is unknown until the data is
extracted.
"""
import argparse
import os
import re
import subprocess
import sys

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..',
                    'wariowareinc-main')
DATA_BYTES = 0x400          # enough for a table head; real sizes come later


def compile_units(outdir, compiler, compat):
    os.makedirs(outdir, exist_ok=True)
    objs, failed = [], []
    # data/ and graphics/ hold the ROM tables that have been converted to C.
    # They define symbols the game code references, so they must be counted
    # here or those names would be stubbed twice.
    roots = [os.path.join(REPO, r) for r in ('src', 'data', 'graphics')]
    roots.append(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              '..', 'pcdata'))
    for root in roots:
      for dp, _, fns in os.walk(root):
        for f in sorted(fns):
            if not f.endswith('.c') or f.endswith('.inc.c'):
                continue
            src = os.path.relpath(os.path.join(dp, f), REPO)
            # Two scenes both have a scene_bs.c, so the object name carries
            # the path.
            obj = os.path.join(outdir,
                               os.path.splitext(src)[0].replace('/', '_') + '.o')
            cmd = [compiler, '-c', '-std=gnu89', '-O1', '-w',
                   '-DWWPC_WIDE_POINTERS',
                   '-I', compat, '-I', '.', '-I', 'include',
                   '-iquote', 'include', "-Dasm(x)=", '-o', obj, src]
            if subprocess.run(cmd, cwd=REPO, capture_output=True).returncode:
                failed.append(src)
            else:
                objs.append(obj)
    return objs, failed


def symbol_split(objs):
    """(undefined, defined) symbol names, with the Mach-O underscore removed."""
    def run(args):
        out = subprocess.run(['nm'] + args + objs, capture_output=True, text=True)
        return out.stdout

    undef = set()
    for line in run(['-u']).splitlines():
        line = line.strip()
        if line.startswith('_'):
            undef.add(line[1:])

    defined = set()
    for line in run(['-g']).splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] not in ('U', 'u'):
            defined.add(parts[2].lstrip('_'))
    return sorted(undef - defined), defined


def game_identifiers():
    """Every identifier that appears anywhere in the decomp.

    Objects passed with --also are the PC shell's, and reference libc and SDL
    alongside the game entry points.  Only names the game itself knows about
    should ever become stubs.
    """
    names = set()
    ident = re.compile(r'\b[A-Za-z_]\w*\b')
    for root in ('src', 'include', 'asm', 'data', 'graphics'):
        for dp, _, fns in os.walk(os.path.join(REPO, root)):
            for f in fns:
                if f.endswith(('.c', '.h', '.s', '.inc')):
                    names.update(ident.findall(
                        open(os.path.join(dp, f), errors='replace').read()))
    return names


def called_names():
    """Everything that is called anywhere, so data and code can be told apart.

    Both halves matter: a function the C never calls may still be reached by a
    BL in assembly, and stubbing it as data turns the call into a jump into a
    zeroed array -- a fault with no name on it.
    """
    names = set()
    call_c = re.compile(r'\b([A-Za-z_]\w*)\s*\(')
    call_asm = re.compile(r'\b(?:BL|BLX)\s+([A-Za-z_]\w*)')
    for root in ('src', 'asm', 'data', 'graphics'):
        for dp, _, fns in os.walk(os.path.join(REPO, root)):
            for f in fns:
                if f.endswith(('.c', '.h')):
                    names.update(call_c.findall(
                        open(os.path.join(dp, f), errors='replace').read()))
                elif f.endswith('.s'):
                    names.update(call_asm.findall(
                        open(os.path.join(dp, f), errors='replace').read()))
    return names


HEADER = '''/* Generated by tools/gen_pc_stubs.py -- do not edit.
 *
 * Every symbol the decompiled C still references but nothing defines yet.
 * Functions report themselves and stop; data is zeroed storage of a nominal
 * size, which is wrong in detail but lets the link succeed so the program can
 * tell us what it needs next.
 *
 * Reporting goes through write(2) rather than stdio: the game headers shadow
 * <stdio.h>, and Homebrew GCC cannot parse the system one on this SDK anyway.
 */
#include <unistd.h>
#include <stdlib.h>
#include <execinfo.h>

static void wwpc_say(const char *s)
{
    size_t n = 0;

    while (s[n]) {
        n++;
    }
    write(2, s, n);
}

static void wwpc_missing(const char *name)
{
    void *frames[24];
    int n;

    wwpc_say("\\n[stub] ");
    wwpc_say(name);
    wwpc_say(" ist noch nicht portiert -- das Spiel kommt bis hierher.\\n");
    /* The call path matters more than the name: it says which scene wanted it.
       backtrace_symbols_fd writes straight to the descriptor, so this works
       even though the game headers shadow <stdio.h>. */
    wwpc_say("Aufrufpfad:\\n");
    n = backtrace(frames, 24);
    backtrace_symbols_fd(frames, n, 2);
    exit(3);
}

'''


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('-o', '--out', default='pc/generated_stubs.c')
    ap.add_argument('--objdir', default='/tmp/wwpc-obj')
    ap.add_argument('--cc', default='gcc-15')
    ap.add_argument('--compat', default=None,
                    help='directory shadowing broken system headers')
    ap.add_argument('--provided', default='pc/provided.txt',
                    help='symbols the runtime defines by hand, one per line')
    ap.add_argument('--also', nargs='*', default=[],
                    help='further objects whose undefined symbols also count -- '
                         'the PC shell references game entry points that no '
                         'game object mentions')
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    compat = args.compat or os.path.join(here, '..', 'pc', 'compat')

    objs, failed = compile_units(args.objdir, args.cc, os.path.abspath(compat))
    if failed:
        print('nicht uebersetzbar:', ', '.join(failed), file=sys.stderr)

    provided = set()
    if os.path.exists(args.provided):
        provided = {l.strip() for l in open(args.provided)
                    if l.strip() and not l.startswith('#')}

    undef, _ = symbol_split(objs)
    also = [o for o in args.also if os.path.exists(o)]
    if also:
        extra, _ = symbol_split(objs + also)
        known = game_identifiers()
        undef = sorted(set(undef) | {s for s in extra if s in known})
    undef = [s for s in undef if s not in provided]
    calls = called_names()

    funcs = [s for s in undef if s in calls]
    data = [s for s in undef if s not in calls]

    with open(args.out, 'w') as fh:
        fh.write(HEADER)
        for s in funcs:
            fh.write('int %s(void) { wwpc_missing("%s"); return 0; }\n' % (s, s))
        fh.write('\n')
        for s in data:
            fh.write('unsigned char %s[0x%X];\n' % (s, DATA_BYTES))

    print('%d Einheiten uebersetzt, %d Symbole offen '
          '(%d Funktionen, %d Datenbloecke)'
          % (len(objs), len(undef), len(funcs), len(data)))
    print('geschrieben: %s' % args.out)


if __name__ == '__main__':
    main()
