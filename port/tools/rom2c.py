#!/usr/bin/env python3
"""Turn a raw ROM block into C, together with the pointer tables inside it.

The decomp keeps data it has not reconstructed yet as a byte blob under bin/,
linked at its ROM address.  That works on the GBA, where a pointer is four
bytes; on a 64-bit host every address stored in such a blob is truncated.

This emits the same block as a C array -- byte for byte, no field types
invented -- and re-expresses the pointer tables named on the command line as
real C pointers into that array.  A table only needs its address, its length
and its element type; everything the table points at stays raw bytes until
somebody reconstructs it properly.

    rom2c.py 0x083A4A80 0x083A8CAC -o out.c \\
        --table 0x083A4B58 29 D_083A4B58 'struct Unk083A4B58 *' \\
        --include src/scenes/gameplay.h
"""

import argparse
import os
import struct
import sys

ROM_BASE = 0x08000000
ROM_DEFAULT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "..", "..", "rom.gba")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("start", help="first ROM address of the block")
    ap.add_argument("end", help="first ROM address after the block")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--rom", default=ROM_DEFAULT)
    ap.add_argument("--include", action="append", default=[],
                    help="header the table types come from; repeatable")
    ap.add_argument("--table", action="append", nargs=4, default=[],
                    metavar=("ADDR", "COUNT", "NAME", "TYPE"),
                    help="a pointer table inside the block; repeatable")
    args = ap.parse_args()

    start, end = int(args.start, 0), int(args.end, 0)
    rom = open(os.path.abspath(args.rom), "rb").read()
    data = rom[start - ROM_BASE:end - ROM_BASE]
    blob = "wwpc_rom_%08X" % start

    out = ["/* Generated by port/tools/rom2c.py from rom.gba -- do not edit.",
           " *",
           " * The ROM block at 0x%08X..0x%08X, verbatim.  None of it is typed:" % (start, end),
           " * these are the cartridge's own bytes.  What is typed is the pointer",
           " * tables below, which the GBA stores as four-byte words and a 64-bit",
           " * host cannot use as they stand.",
           " */"]
    for h in args.include:
        out.append('#include "%s"' % h)
    if not args.include:
        out.append('#include "global.h"')
    out.append("")
    out.append("u8 %s[0x%X] = {" % (blob, len(data)))
    for i in range(0, len(data), 16):
        out.append("    " + " ".join("0x%02X," % b for b in data[i:i + 16]))
    out.append("};")
    out.append("")

    for addr, count, name, ctype in args.table:
        addr, count = int(addr, 0), int(count, 0)
        out.append("/* 0x%08X */" % addr)
        out.append("%s%s[%d] = {" % (ctype, name, count))
        for i in range(count):
            off = addr - start + 4 * i
            value = struct.unpack_from("<I", data, off)[0]
            if value == 0:
                out.append("    NULL,")
            elif start <= value < end:
                out.append("    (%s)(%s + 0x%X),   /* 0x%08X */"
                           % (ctype.strip(), blob, value - start, value))
            else:
                # Outside the block: nothing to point at yet, so say so rather
                # than fabricate an address.
                out.append("    NULL,   /* 0x%08X liegt ausserhalb des Blocks */" % value)
        out.append("};")
        out.append("")

    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    open(args.output, "w").write("\n".join(out) + "\n")
    print("0x%08X..0x%08X: %d Bytes, %d Tabelle(n) -> %s"
          % (start, end, len(data), len(args.table), args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
