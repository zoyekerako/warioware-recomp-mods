ROWS = 8

def g(ch, *rows):
    """7 Zeilen werden unten mit einer Leerzeile aufgefuellt, 8 gelten
    unveraendert -- so behalten Versalien und Ziffern ihre Form, waehrend
    Unterlaengen die achte Zeile nutzen duerfen."""
    rows = list(rows)
    if len(rows) == 7:
        rows.append('.....')
    assert len(rows) == ROWS, (ch, len(rows))
    for r in rows:
        assert len(r) == 5, (ch, r, len(r))
    G[ch] = rows

