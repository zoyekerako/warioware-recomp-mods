FIRST, LAST = 0x20, 0x7A
out = []
for c in range(FIRST, LAST + 1):
    ch = chr(c)
    rows = G.get(ch)
    if rows is None:
        rows = G['?'] if ch not in ('\\', '^', '`', '{', '|', '}', '~', '$', '&', ';', '@') else G[' ']
    cols = []
    for x in range(5):
        b = 0
        for y in range(ROWS):
            if rows[y][x] == '#':
                b |= (1 << y)
        cols.append(b)
    out.append((ch, cols))

# Vorschau zur Sichtkontrolle
def preview(text):
    lines = ['' for _ in range(ROWS)]
    for ch in text:
        cols = dict(out).get(ch)
        if cols is None:
            continue
        for y in range(ROWS):
            for x in range(5):
                lines[y] += '#' if (cols[x] >> y) & 1 else '.'
            # kein Trenner noetig
        for y in range(ROWS):
            lines[y] += '.'
    return '\n'.join(lines)

